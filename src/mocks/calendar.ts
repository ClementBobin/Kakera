const base = new Date('2026-04-13T00:00:00.000Z')

function daysFromBase(days: number, hour = 16): string {
  const d = new Date(base)
  d.setDate(d.getDate() + days)
  d.setUTCHours(hour, 0, 0, 0)
  return d.toISOString()
}

